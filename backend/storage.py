import os
import re
import tempfile
import time
from pathlib import Path

import requests

APP_NAME = "arabic-rsvp-reader"
CACHE_DIR = Path(os.environ.get("PDF_CACHE_DIR", "/tmp/pdfcache"))
CACHE_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
try:
    CACHE_DIR.chmod(0o700)
except OSError:
    pass

_storage_key = None
_SAFE_COMPONENT = re.compile(r"^[A-Za-z0-9._/-]+$")


def _url() -> str:
    base = (os.environ.get("INTEGRATION_PROXY_URL") or "").strip() or "https://integrations.emergentagent.com"
    return base.rstrip("/") + "/objstore/api/v1/storage"


def init_storage(force: bool = False) -> str:
    global _storage_key
    if _local_dir():
        return "local"
    if _storage_key and not force:
        return _storage_key
    resp = requests.post(f"{_url()}/init", json={"emergent_key": os.environ["EMERGENT_LLM_KEY"]}, timeout=30)
    resp.raise_for_status()
    _storage_key = resp.json()["storage_key"]
    return _storage_key


def _validate_object_path(path: str) -> str:
    if not isinstance(path, str) or not path or len(path) > 512 or "\\" in path:
        raise ValueError("invalid storage path")
    # Paths are generated by the application; reject traversal even if a DB record is tampered with.
    parts = Path(path).parts
    if any(part in ("", ".", "..") for part in parts) or not _SAFE_COMPONENT.fullmatch(path):
        raise ValueError("invalid storage path")
    return path


def _local_target(path: str) -> Path:
    root = _local_dir()
    if not root:
        raise RuntimeError("local storage is not configured")
    root = root.expanduser().resolve()
    target = (root / _validate_object_path(path)).resolve()
    if target != root and root not in target.parents:
        raise ValueError("invalid storage path")
    return target


def _request(method: str, path: str, **kwargs) -> requests.Response:
    path = _validate_object_path(path)
    force = False
    for attempt in range(4):
        headers = {"X-Storage-Key": init_storage(force=force), **kwargs.pop("headers", {})}
        resp = requests.request(method, f"{_url()}/objects/{path}", headers=headers, **kwargs)
        kwargs["headers"] = {k: v for k, v in headers.items() if k != "X-Storage-Key"}
        if resp.status_code == 404 and not force:
            force = True
            continue
        if (resp.status_code >= 500 or resp.status_code == 429) and attempt < 3:
            time.sleep(1.5 * (attempt + 1))
            continue
        resp.raise_for_status()
        return resp
    resp.raise_for_status()
    return resp


def _local_dir():
    # self-hosting: set STORAGE_DIR to keep files on local disk instead of Emergent object storage
    d = os.environ.get("STORAGE_DIR")
    return Path(d) if d else None


def _atomic_write(target: Path, data: bytes):
    target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, tmp = tempfile.mkstemp(prefix=".upload-", dir=str(target.parent))
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, target)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def put_object(path: str, data: bytes, content_type: str) -> dict:
    path = _validate_object_path(path)
    local = _local_dir()
    if local:
        target = _local_target(path)
        _atomic_write(target, data)
        return {"path": path, "size": len(data)}
    return _request("PUT", path, headers={"Content-Type": content_type}, data=data, timeout=180).json()


def get_object(path: str) -> bytes:
    path = _validate_object_path(path)
    local = _local_dir()
    if local:
        return _local_target(path).read_bytes()
    return _request("GET", path, timeout=120).content


def _cache_path(document_id: str) -> Path:
    if not re.fullmatch(r"[a-f0-9]{32}", document_id or ""):
        raise ValueError("invalid document id")
    return CACHE_DIR / f"{document_id}.pdf"


def get_pdf_bytes(document_id: str, storage_path: str) -> bytes:
    cached = _cache_path(document_id)
    if cached.exists():
        return cached.read_bytes()
    data = get_object(storage_path)
    _atomic_write(cached, data)
    return data


def cache_pdf(document_id: str, data: bytes):
    _atomic_write(_cache_path(document_id), data)


def drop_cache(document_id: str):
    _cache_path(document_id).unlink(missing_ok=True)
